#!/usr/bin/env python3
"""control_map.json -> vst/params.json (VST parameter list, order = VST index) and src/params_gen.h (C enum + names)."""
import json, os, re
H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(H, "..")
d = json.load(open(os.path.join(R, "vst", "control_map.json")))
NAMED = {'gate_s1','gate_s2','gate_s3','gate_s4','gate_s5','gate_s6','gate_s7','gate_s8','gate_cg','osc_wav','osc_sub','lfo_wav','lfo_mde','lfo_dst','lfo_syn','perf_gtp','perf_mon','arp_src','arp_typ','arp_hld','arp_vel','arp_oct','arp_tmp','echo_tim','p7_mod_bar_mde','p7_mod_bar_dst','p7_split_son','p8_chorus_on','p8_crush_src','p9_voice_mna','p9_voice_mnb','p10_ribbon_rib','p10_sustain_smd'}
params, secs = [], []
for p in d["pages"]:
    keys = []
    for c in p["controls"]:
        k = c["id"]; blk = c.get("block", "")
        nm = ("%s %s" % (blk, c["label"])).strip().upper()
        if c["kind"] == "button":
            params.append({"key": k, "name": c["label"].upper(), "min": 0, "max": 1, "momentary": True, "debounce_ms": 0})
        else:
            ent = {"key": k, "name": nm, "min": 0, "max": 100, "default": round(c["pos"] * 100), "display": "int"}
            if re.sub(r"^p\d+_[ab]_", "", k) in NAMED: ent["dynamic_display"] = True   # engine answers <key>_display with the value's name
            params.append(ent)
        keys.append(k)
    secs.append({"label": "%d %s" % (p["index"], p["name"]), "keys": keys})
# ---- page navigation (one tab, pages shown by pg_N, tapped from the overview) + Q-Links that follow the page
NPG = len(d["pages"])
VIEW_QL = [[] for _ in range(NPG + 1)]
for p in d["pages"]:
    VIEW_QL[p["index"]] = [c["id"] for c in p["controls"] if c["kind"] == "slider"][:32]
for i in range(1, 33):
    params.append({"key": "ql%d" % i, "name": "Q-Link %d" % i, "min": 0.0, "max": 1.0, "default": 0.0, "dynamic_name": True, "dynamic_display": True})
for k, nm in (("nav_zoom", "OVERVIEW"), ("nav_prev", "PREVIOUS PAGE"), ("nav_next", "NEXT PAGE")):
    params.append({"key": k, "name": nm, "min": 0.0, "max": 1.0, "default": 0.0, "momentary": True, "debounce_ms": 0, "type": "trigger", "refresh_display": True})
for p in d["pages"]:
    params.append({"key": "go_%d" % p["index"], "name": "GO " + p["name"], "min": 0.0, "max": 1.0, "default": 0.0, "momentary": True, "debounce_ms": 0, "type": "trigger", "refresh_display": True})
for i in range(NPG + 1):
    params.append({"key": "pg_%d" % i, "name": "PAGE %d" % i, "options": ["Off", "On"], "default": 0})
# ---- preset list (KutilXXL style): 8 named rows, page up/down, status line (appended after pg_N: params.lock is append-only)
for i in range(1, 9):
    params.append({"key": "pm_%d" % i, "name": "Preset Row %d" % i, "min": 0.0, "max": 1.0, "default": 0.0, "display": "string", "type": "slot"})
for k, nm in (("pm_prev", "PRESETS PAGE UP"), ("pm_next", "PRESETS PAGE DOWN"), ("pm_prev10", "PRESETS -10 PAGES"), ("pm_next10", "PRESETS +10 PAGES")):
    params.append({"key": k, "name": nm, "min": 0.0, "max": 1.0, "default": 0.0, "momentary": True, "debounce_ms": 0, "type": "trigger", "refresh_display": True})
params.append({"key": "pm_info", "name": "Preset Info", "min": 0.0, "max": 1.0, "default": 0.0, "display": "string"})
json.dump({"name": "CSXXL", "params": params, "sections": secs}, open(os.path.join(R, "vst", "params.json"), "w"), indent=1)
with open(os.path.join(R, "src", "params_gen.h"), "w") as f:
    f.write("/* generated by tools/gen_params.py - do not edit */\n#pragma once\nenum {\n")
    for q in params:
        f.write("  E_%s,\n" % q["key"])
    f.write("  N_PARAMS\n};\n")
    f.write("static const char *const PKEY[N_PARAMS] = {\n" + ",\n".join('  "%s"' % q["key"] for q in params) + "\n};\n")
    f.write("static const unsigned char PDEF[N_PARAMS] = {" + ",".join(str(q.get("default", 0)) for q in params) + "};\n")
    f.write("static const unsigned char PBTN[N_PARAMS] = {" + ",".join("1" if q.get("momentary") else "0" for q in params) + "};\n")
    # per-layer parameter table: index [layer][slot]
    LAY = ["osc_wav","osc_wlv","osc_plv","osc_wid","osc_pw","osc_rte","osc_sub",
           "lpf_frq","lpf_res","lpf_att","lpf_dec","lpf_sus","lpf_rel","lpf_mod",
           "hpf_frq","hpf_res","hpf_att","hpf_dec","hpf_sus","hpf_rel","hpf_mod",
           "amp_sine","amp_flt","amp_att","amp_dec","amp_sus","amp_rel","amp_lvl",
           "lfo_rte","lfo_syn","lfo_wav","lfo_mde","lfo_dst","lfo_att","lfo_rel",
           "vib_lfo","vib_vib","vib_vrt","vib_slo","vib_shi",
           "touch_lve","touch_hve","touch_laf","touch_haf","touch_mix","touch_key",
           "echo_tim","echo_rep","echo_lvl","echo_dly",
           "perf_glid","perf_gtp","perf_tun","perf_oct","perf_bnd","perf_mon","perf_ft",
           "arp_src","arp_typ","arp_hld","arp_tmp","arp_oct","arp_vel","arp_gat",
           "cs80_il","cs80_al","cs80_ibr","cs80_abr","cs80_ilv","cs80_alv",
           "gate_s1","gate_s2","gate_s3","gate_s4","gate_s5","gate_s6","gate_s7","gate_s8","gate_cg"]
    pageof = {}
    for p in d["pages"]:
        for c in p["controls"]:
            pageof[c["id"]] = p["index"]
    keyset = {q["key"] for q in params}
    f.write("enum {\n" + ",\n".join("  L_%s" % n.upper() for n in LAY) + ",\n  N_LAYER\n};\n")
    f.write("static const int LIDX[2][N_LAYER] = {\n")
    for ly in "ab":
        row = []
        for n in LAY:
            found = [k for k in keyset if re.fullmatch(r"p\d+_%s_%s" % (ly, n), k)]
            row.append("E_%s" % found[0] if found else "-1")
        f.write("  {" + ", ".join(row) + "},\n")
    f.write("};\n")
pk = {q["key"]: i for i, q in enumerate(params)}
f = open(os.path.join(R, "src", "params_gen.h"), "a")
f.write("#define N_PAGES %d\n" % NPG)
f.write("static const short VIEW_QL[N_PAGES + 1][32] = {\n")
for row in VIEW_QL:
    f.write("  {" + ", ".join(str(pk[k]) if k else "-1" for k in (row + [None] * 32)[:32]) + "},\n")
f.write("};\nstatic const char *const PNAME[N_PARAMS] = {\n" + ",\n".join('  "%s"' % q["name"] for q in params) + "\n};\n")
f.close()
print(len(params), "params")
