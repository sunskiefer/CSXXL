#!/usr/bin/env python3
"""Generate vst/layout.conf + vst/art/ from the control map, colours and rendered panels."""
import json,os,shutil,sys
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src=sys.argv[1]            # dir holding pN/page.png and pN/cap_sprite_*.png (or ../p6 sprites)
v=os.path.join(root,'vst'); art=os.path.join(v,'art'); os.makedirs(art,exist_ok=True)
m=json.load(open(v+'/control_map.json')); col=json.load(open(v+'/line_colours.json'))
for c in ['yellow','blue','green','red','white']:
    f=os.path.join(src,'p6','cap_sprite_%s.png'%c)
    if os.path.exists(f): shutil.copy(f,art+'/cap_%s.png'%c)
out=['# CSXXL layout (generated by tools/gen_layout.py)','art_css=skin.css']
for p in m['pages']:
    n=p['index']; bg=os.path.join(src,'p%d'%n,'page.png')
    out.append('[tab %s]'%p['name'])
    if os.path.exists(bg):
        shutil.copy(bg,art+'/page%d.png'%n); out.append('art file=art/page%d.png fit=stretch'%n)
    keys=[]
    for c in p['controls']:
        cx=c['x']+c['w']//2; cy=c['y']+c['h']//2+86
        if c['kind']=='slider':
            cc=col.get(c['id'],{}); cc=cc.get('colour','red') if isinstance(cc,dict) else cc
            out.append('slider_v cx=%d cy=%d w=%d h=%d label="%s" key=%s img=art/cap_%s.png ns=0 vs=0 bw=%d'%(cx,cy,c['w'],c['h'],c['label'],c['id'],cc,c['w']+30))
            keys.append(c['id'])
        else:
            out.append('button cx=%d cy=%d label="%s" key=%s'%(cx,cy,c['label'],c['id']))
    if keys: out.append('qlinks "%s" = %s'%(p['name'],','.join(keys[:16])))
open(v+'/layout.conf','w').write('\n'.join(out)+'\n')
print('ok',len(out))
