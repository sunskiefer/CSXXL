#!/usr/bin/env python3
"""Generate vst/layout.conf + vst/art/ from the control map, colours and rendered panels."""
import json,os,shutil,sys
from PIL import Image
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src=sys.argv[1]            # dir holding pN/page.png and pN/cap_sprite_*.png (or ../p6 sprites)
v=os.path.join(root,'vst'); art=os.path.join(v,'art'); os.makedirs(art,exist_ok=True)
m=json.load(open(v+'/control_map.json')); col=json.load(open(v+'/line_colours.json'))
for c in ['yellow','blue','green','red','white']:
    f=os.path.join(src,'p6','cap_sprite_%s.png'%c)
    if os.path.exists(f): shutil.copy(f,art+'/cap_%s.png'%c)
import subprocess
subprocess.check_call([sys.executable,os.path.join(root,'tools','gen_overview.py'),src])
tiles=json.load(open(v+'/overview_tiles.json'))
QL=','.join('ql%d'%i for i in range(1,17)); QL2=','.join('ql%d'%i for i in range(17,33))
# black cap line: the white sprite with its indicator darkened (where the red sprite differs from the white one)
if all(os.path.exists(art+'/cap_%s.png'%x) for x in ('red','white')):
    red=Image.open(art+'/cap_red.png').convert('RGBA'); wh=Image.open(art+'/cap_white.png').convert('RGBA'); bk=wh.copy(); px=bk.load(); pr=red.load(); pw_=wh.load()
    for yy in range(bk.height):
        for xx in range(bk.width):
            if sum(abs(pr[xx,yy][i]-pw_[xx,yy][i]) for i in range(3))>60 and pw_[xx,yy][3]>0: px[xx,yy]=(24,24,26,pw_[xx,yy][3])
    bk.save(art+'/cap_black.png')
out=['# CSXXL layout (generated by tools/gen_layout.py): one tab; the overview and each page are shown by their pg_N switch','art_css=skin.css','theme_lcd=101010','theme_tile_on=8a2a2a','qlinks_track = '+QL,'[tab CSXXL]']
out.append('art file=art/overview.png fit=stretch when=pg_0:1')
for t in tiles:
    out.append('button cx=%d cy=%d label="" key=go_%d when=pg_0:1'%(t['x']+t['w']//2,t['y']+t['h']//2+86,t['page']))
# header buttons are drawn in the panel art on every page; these sit on them
out.append('button cx=96 cy=122 label="OVERVIEW" key=nav_zoom')
out.append('button cx=213 cy=122 label="<" key=nav_prev')
out.append('button cx=277 cy=122 label=">" key=nav_next')
PM_BTN=[('LOAD','p11_load',840,300),('SAVE','p11_save',1010,300),('INIT','p11_init',1180,300),('PAGE UP','pm_prev',840,420),('PAGE DOWN','pm_next',1010,420),('INIT ALL',None,0,0)][:5]
PM_BTN+= [('-10 PAGES','pm_prev10',840,540),('+10 PAGES','pm_next10',1010,540)]
PM_KEY={b[0]:b[1] for b in PM_BTN if False}
PM_BTN=[(a,c,d) for a,b,c,d in PM_BTN]
for p in m['pages']:
    n=p['index']; bg=os.path.join(src,'p%d'%n,'page.png'); W='when=pg_%d:1'%n
    if os.path.exists(bg):
        shutil.copy(bg,art+'/page%d.png'%n); out.append('art file=art/page%d.png fit=stretch %s'%(n,W))
        # page title in the header: "n/<count>  NAME" (repainted so the count follows the number of pages)
        from PIL import ImageDraw as _ID, ImageFont as _IF
        _hp=Image.open(art+'/page%d.png'%n).convert('RGB'); _d=_ID.Draw(_hp)
        _d.rectangle([322,8,690,62],fill=(0,0,0))
        _d.text((340,48),'%d/%d  %s'%(n,len(m['pages']),p['name']),font=_IF.truetype(os.path.join(os.environ.get('MPC_VST','/home/claude/sunskiefer/mpc-vst-plugins'),'tools/html_art/fonts/TitilliumWeb-SemiBold.ttf'),34),fill=(245,245,245),anchor='ls')
        if n==11:   # preset page: KutilXXL-style list picker; clear the old BNK/PAT body and the baked LCD text, draw the right-hand buttons
            _fnt=_IF.truetype(os.path.join(os.environ.get('MPC_VST','/home/claude/sunskiefer/mpc-vst-plugins'),'tools/html_art/fonts/TitilliumWeb-SemiBold.ttf'),28)
            _d.rectangle([0,70,1279,627],fill=(205,206,211)); _d.rectangle([703,8,1266,62],fill=(0,0,0))
            for _lb,_x,_y in PM_BTN: _d.rounded_rectangle([_x-82,_y-86-40,_x+82,_y-86+40],radius=12,outline=(60,60,66),width=3); _d.text((_x,_y-86),_lb,font=_fnt,fill=(30,30,34),anchor='mm')
        _hp.save(art+'/page%d.png'%n)
    if n==11:
        out.append('list x=24 y=170 w=720 h=474 key=pm cols=1 rows=8 th=54 gap=6 %s'%W)
        out.append('readout cx=1010 cy=196 w=470 h=64 label="" key=pm_info %s'%W)
        for (lb,x,y),k in zip(PM_BTN,['p11_load','p11_save','p11_init','pm_prev','pm_next','pm_prev10','pm_next10']):
            out.append('button cx=%d cy=%d label="%s" key=%s %s'%(x,y,lb,k,W))
        continue
    for c in p['controls']:
        cx=c['x']+c['w']//2; cy=c['y']+c['h']//2+86
        if c['kind']=='slider':
            cc=col.get(c['id'],{}); cc=cc.get('colour','red') if isinstance(cc,dict) else cc
            out.append('slider_v cx=%d cy=%d w=%d h=%d label="%s" key=%s img=art/cap_%s.png ns=0 vs=0 bw=%d %s'%(cx,cy,c['w'],c['h'],c['label'],c['id'],cc,c['w']+30,W))
        else:
            out.append('button cx=%d cy=%d label="%s" key=%s %s'%(cx,cy,c['label'],c['id'],W))
# the touch ribbon stripe is baked into the VOICE page (pad/layout.txt gives its place) so it is always visible; the plugin's overlay draws the live part on top
from PIL import Image, ImageDraw, ImageFont
px,py,pw,ph=[int(t) for t in open(os.path.join(root,'pad','layout.txt')).read().split()[1:5]]
vp=art+'/page10.png'; im=Image.open(vp).convert('RGB'); S=4
st=Image.new('RGBA',(pw*S,ph*S),(0,0,0,0)); d=ImageDraw.Draw(st)
d.rounded_rectangle([0,0,pw*S-1,ph*S-1],radius=ph*S//2,fill=(96,96,98,255)); d.rounded_rectangle([2*S,2*S,pw*S-1-2*S,ph*S-1-2*S],radius=ph*S//2-2*S,fill=(14,14,14,255))
d.rectangle([pw*S//2-S,ph*S//4,pw*S//2+S,ph*S*3//4],fill=(74,74,74,255))
st=st.resize((pw,ph),Image.LANCZOS); im.paste(st,(px,py),st)
fnt=ImageFont.truetype(os.path.join(os.environ.get('MPC_VST','/home/claude/sunskiefer/mpc-vst-plugins'),'tools/html_art/fonts/TitilliumWeb-SemiBold.ttf'),28)
ImageDraw.Draw(im).text((px+pw//2,py-18),'TOUCH RIBBON',font=fnt,fill=(40,40,44),anchor='mm'); im.save(vp)
out.append('qlinks "CSXXL 1" = '+QL); out.append('qlinks "CSXXL 2" = '+QL2)
open(v+'/layout.conf','w').write('\n'.join(out)+'\n')
print('ok',len(out))
