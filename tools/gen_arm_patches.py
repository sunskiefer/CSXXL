#!/usr/bin/env python3
"""Converts Arminator2 .fxb banks into CSXXL factory patches (src/arm_patches.h, docs/ARM_PATCHES.md).
usage: gen_arm_patches.py <folder with the .fxb banks>
Each bank holds 182 arrays (one parameter over 128 patches). tools/arm_map.json says which array is which named parameter
(array index, nominal low, nominal high); the value is scaled to 0..1 and written as a 0..100 slider position.
Controls whose array is not matched stay at the neutral CSXXL layer."""
import os, sys, json, struct, glob
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BANKS = ["Arminator Default Bank", "Arminator Factory Re-tuned", "Arminator Kujashi Bank II", "Arminator Kujashi Bank III", "Arminator Kujashi Bank IV"]
LINE = {"Amp Attack": "AMP_ATT", "Amp Decay": "AMP_DEC", "Amp Sustain": "AMP_SUS", "Amp Release": "AMP_REL", "Amp Level": "AMP_LVL", "Filter to Amp Level": "AMP_FLT",
        "sine Osc Level": "AMP_SINE", "Sine Osc Level": "AMP_SINE", "Saw Osc Level": "OSC_WLV", "saw Osc Waveform": "OSC_WAV", "PWM Osc Level": "OSC_PLV", "PWM Osc Width": "OSC_WID",
        "PWM Osc PWM": "OSC_PW", "PWM Osc Rate": "OSC_RTE", "LPF Freq": "LPF_FRQ", "LPF Resonance": "LPF_RES", "LPF Attack": "LPF_ATT", "LPF Decay": "LPF_DEC", "LPF Sustain": "LPF_SUS",
        "LPF Release": "LPF_REL", "LPF Env Mod": "LPF_MOD", "LPF Velocity": "TOUCH_LVE", "LPF Aftertouch": "TOUCH_LAF", "HPF Freq": "HPF_FRQ", "HPF Resonance": "HPF_RES",
        "HPF Attack": "HPF_ATT", "HPF Decay": "HPF_DEC", "HPF Sustain": "HPF_SUS", "HPF Release": "HPF_REL", "HPF Env Mod": "HPF_MOD", "HPF Velocity": "TOUCH_HVE", "HPF Aftertouch": "TOUCH_HAF",
        "LFO Rate": "LFO_RTE", "LFO Attack": "LFO_ATT", "LFO Release": "LFO_REL", "LFO Mod Amount": "LFO_MDE", "LFO Mod Destination": "LFO_DST", "Vibrato Rate": "VIB_VRT",
        "SampleHold Hi Range": "VIB_SHI", "SampleHold Lo Range": "VIB_SLO", "Echo Mix": "ECHO_LVL", "Echo Repeat": "ECHO_REP", "Echo Clock Mode": "ECHO_TIM", "Note Tune": "PERF_TUN",
        "Fine Tune": "PERF_TUN", "Octave": "PERF_OCT", "Clock Divide": "ARP_TMP", "Arp Clock Divide": "ARP_TMP", "Arp Mode": "ARP_TYP"}
for i in range(8): LINE["Arp Gate Step %d" % (i + 1)] = "GATE_S%d" % (i + 1)
GLOB = {"Reverb Damp": "p8_reverb_dmp", "Reverb Mix": "p8_reverb_mix", "Reverb Size": "p8_reverb_size", "Reverb Width": "p8_reverb_wid",
        "Ring Mod Input Line A B Mix": "p8_ring_mod_ab", "Ring Mod Volume Envelope Mod": "p8_ring_mod_ven", "Ring Mod Pitch": "p8_ring_mod_pit", "Ring Mod Attack": "p8_ring_mod_att",
        "Ring Mod Decay": "p8_ring_mod_dec", "Ring Mod Pitch Envelope Mod": "p8_ring_mod_pen", "Ring Mod Velocity": "p8_ring_mod_pvl", "Ring Mod Mixer Volume": "p9_levels_rm",
        "Ring Mod Mixer Pan": "p9_pans_prm", "Bit Crush Mixer Volume": "p9_levels_bitc", "Bit Crush Mixer Pan": "p9_pans_pbc", "Volume": "p9_main_out"}
def mixer(nm):
    return {"A Mixer Volume": ("p9_levels_a"), "B Mixer Volume": "p9_levels_b", "A Mixer Pan": "p9_pans_pa", "B Mixer Pan": "p9_pans_pb"}.get(nm)

def parse(path):
    d = open(path, "rb").read()
    p = d.find(b"\xff\xfe\xff"); names = []
    while d[p:p + 3] == b"\xff\xfe\xff":
        n = d[p + 3]; names.append(d[p + 4:p + 4 + 2 * n].decode("utf-16le")); p += 4 + 2 * n
    pos = []; i = p - 4
    while True:
        i = d.find(b"\x80\x00\x00\x00", i + 1)
        if i < 0: break
        t = struct.unpack("<I", d[i - 4:i])[0]
        if t in (0, 6) and i + 516 <= len(d): pos.append((i, t))
    arr = [list(struct.unpack("<128f" if t == 6 else "<128i", d[i + 4:i + 516])) for i, t in pos]
    if len(arr) != 182: raise SystemExit("%s: %d arrays, expected 182" % (path, len(arr)))
    return names, arr

folder = sys.argv[1]
amap = json.load(open(os.path.join(R, "tools", "arm_map.json")))
entries = []   # (kind, a, b, array, lo, hi)
for nm, (k, lo, hi) in amap.items():
    if nm in GLOB: entries.append(("g", GLOB[nm], None, k, lo, hi)); continue
    m = mixer(nm)
    if m: entries.append(("g", m, None, k, lo, hi)); continue
    side, rest = (nm[0], nm[2:]) if nm[:2] in ("A ", "B ") else (None, nm)
    if side and rest in LINE: entries.append(("l", LINE[rest], side, k, lo, hi))
out = ["/* generated by tools/gen_arm_patches.py - do not edit */", "#pragma once", "#define NARM 640", "#define NARMMAP %d" % len(entries),
       "typedef struct { char kind; short slot; char line; } ArmMap;", "static const ArmMap ARM_MAP[NARMMAP] = {"]
for kind, s, side, k, lo, hi in entries:
    if kind == "g": out.append("  {'g', E_%s, 0}," % s)
    else: out.append("  {'l', L_%s, %d}," % (s, 0 if side == "A" else 1))
out.append("};")
vals = []; names_all = []
for b in BANKS:
    names, arr = parse(os.path.join(folder, b + ".fxb")); names_all += [(b, n) for n in names]
    for p in range(128):
        row = []
        for kind, s, side, k, lo, hi in entries:
            n = (arr[k][p] - lo) / float(hi - lo)
            row.append(int(round(min(1.0, max(0.0, n)) * 100)))
        vals.append(row)
out.append("static const unsigned char ARM_VAL[NARM][NARMMAP] = {")
for row in vals: out.append("{" + ",".join(map(str, row)) + "},")
out.append("};")
def _cs(n):
    n = "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else "?" for c in n.strip())[:23]
    return '"%s"' % n
out.append("static const char *const ARM_NAME[NARM] = {")
out.append(",".join(_cs(n) for b, n in names_all))
out.append("};")
open(os.path.join(R, "src", "arm_patches.h"), "w").write("\n".join(out) + "\n")
md = ["# CSXXL factory patches from the Arminator banks", "", "Slots 1..640 follow the five Arminator banks in this order (128 each): " + ", ".join(BANKS) + ". Slots 641..768 are the written recipes.", ""]
for i, (b, n) in enumerate(names_all): md.append("%d. %s  (%s)" % (i + 1, n, b))
open(os.path.join(R, "docs", "ARM_PATCHES.md"), "w").write("\n".join(md) + "\n")
print("mapped controls:", len(entries), " patches:", len(vals))
